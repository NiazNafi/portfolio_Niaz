// ── Audit ───────────────────────────────────────────────────────────────────

/**
 * Requirements §9 forbids a few things reaching the built output. Cheap to
 * check mechanically, expensive to notice by eye at 2am before an interview.
 */
function audit(c) {
  const blob = JSON.stringify(c);
  const problems = [];
  const gaps = [];

  // §3: never publish the phone number. Any Bangladeshi mobile shape at all.
  if (/(?:\+?880|\b01)\d[\s-]?\d{4}[\s-]?\d{4}\b/.test(blob)) {
    problems.push("a phone number appears in the content");
  }
  if (/lorem ipsum/i.test(blob)) problems.push("lorem ipsum in the content");

  // Referee names are not in the content module at all; assert that stays true.
  if (/referee/i.test(blob)) problems.push("the word 'referee' appears");

  // Every TODO marker becomes a visible gap on the site and a line in the report.
  const walk = (node, trail) => {
    if (!node || typeof node !== "object") return;
    if (typeof node.__todo === "string") {
      gaps.push(`${trail}: ${node.__todo}`);
      return;
    }
    for (const [k, v] of Object.entries(node)) walk(v, trail ? `${trail}.${k}` : k);
  };
  walk(c, "");

  if (c.site.urlIsPlaceholder) {
    gaps.push("site.url: canonical domain is a placeholder (BLOCKING-2)");
  }
  if (!existsSync(path.join(root, "client/public/cv.pdf"))) {
    gaps.push("client/public/cv.pdf: missing — run `npm run assets`");
  }

  return { problems, gaps };
}

// ── Run ─────────────────────────────────────────────────────────────────────

const seed = buildSeed(content);
await mkdir(path.join(root, "supabase/migrations"), { recursive: true });
await writeFile(path.join(root, "supabase/migrations/0002_portfolio_seed.sql"), seed, "utf8");

await mkdir(path.join(root, "client/src/data"), { recursive: true });
await writeFile(
  path.join(root, "client/src/data/content.json"),
  JSON.stringify(content, null, 2) + "\n",
  "utf8",
);

const { problems, gaps } = audit(content);

console.log("generated:");
console.log("  supabase/migrations/0002_portfolio_seed.sql");
console.log("  client/src/data/content.json");

if (gaps.length) {
  console.log(`\nstill missing (${gaps.length}) — see docs/OPEN-ITEMS.md:`);
  for (const g of gaps) console.log(`  · ${g}`);
}

if (problems.length) {
  console.error(`\nWILL NOT SHIP (${problems.length}):`);
  for (const p of problems) console.error(`  ! ${p}`);
  process.exit(1);
}

// Keep the README's asset table honest about how many pieces exist.
const readme = path.join(root, "README.md");
if (existsSync(readme)) {
  const text = await readFile(readme, "utf8");
  const next = text.replace(
    /(<!-- counts -->)[\s\S]*?(<!-- \/counts -->)/,
    `$1\n${content.ambigrams.length} ambigrams · ${content.projects.length} projects · ${content.experience.length} roles\n$2`,
  );
  if (next !== text) await writeFile(readme, next, "utf8");
}
