/**
 * Derives the two generated artefacts from content/source.mjs:
 *
 *   supabase/migrations/0002_portfolio_seed.sql  — what the database holds
 *   client/src/data/content.json                 — what the bundle ships
 *
 * Keeping one authored source and generating both is the point: the API and
 * the offline fallback can never drift into saying different things about the
 * same job.
 *
 * Also audits the content for anything the requirements forbid shipping
 * (§9: no invented metrics, no placeholder text, no phone number) and for
 * assets that are still missing, and prints both lists.
 */

import { mkdir, readFile, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import content from "../content/source.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

// ── SQL literal helpers ─────────────────────────────────────────────────────

const sqlText = (v) =>
  v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`;

const sqlJson = (v) =>
  v === null || v === undefined ? "null" : `${sqlText(JSON.stringify(v))}::jsonb`;

const sqlBool = (v) => (v ? "true" : "false");
const sqlNum = (v) => (v === null || v === undefined ? "null" : String(v));

/** One INSERT ... ON CONFLICT DO UPDATE per table, so re-running is safe. */
function upsert(table, columns, rows) {
  if (!rows.length) return `-- ${table}: nothing to seed\n`;
  const cols = columns.map((c) => c.name);
  // The row index is passed through because some columns are derived from
  // position rather than from the row — experience order, for one.
  const values = rows
    .map((row, i) => `  (${columns.map((c) => c.value(row, i)).join(", ")})`)
    .join(",\n");
  const updates = cols
    .filter((c) => c !== "id")
    .map((c) => `${c} = excluded.${c}`)
    .join(",\n    ");
  return (
    `insert into public.${table} (${cols.join(", ")}) values\n${values}\n` +
    `on conflict (id) do update set\n    ${updates};\n`
  );
}

